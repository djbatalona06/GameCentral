// Exports every playable chapter's level geometry to assets-src/blender/levels.json, so the
// Blender script can build terrain that fits around the playable area (and never pokes into it).
//
//   npm run export-levels
//
// It loads the real chapter code through Vite, so the JSON always matches the game.
import { createServer } from "vite";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "assets-src", "blender", "levels.json");

const server = await createServer({ root, logLevel: "error", server: { middlewareMode: true }, appType: "custom" });
try {
  const { CHAPTERS } = await server.ssrLoadModule("/src/sim/chapters/registry.ts");
  const r = (n) => Math.round(n * 100) / 100;
  const levels = {};
  for (const ch of CHAPTERS) {
    if (!ch.playable || !ch.build) continue;
    const l = ch.build();
    levels[ch.id] = {
      killY: l.killY,
      sky: l.sky,
      // [minX, minY, minZ, maxX, maxY, maxZ, flags]  flags: 1 = boundary (invisible edge), 2 = cover, 4 = hidden at start
      boxes: l.boxes.map((b) => [r(b.min.x), r(b.min.y), r(b.min.z), r(b.max.x), r(b.max.y), r(b.max.z), (b.boundary ? 1 : 0) | (b.cover ? 2 : 0) | (b.hidden ? 4 : 0)]),
      ramps: l.ramps.map((p) => [r(p.min.x), r(p.min.y), r(p.min.z), r(p.max.x), r(p.max.y), r(p.max.z)]),
      water: l.water.map((w) => [r(w.min.x), r(w.min.y), r(w.min.z), r(w.max.x), r(w.max.y), r(w.max.z)]),
      checkpoints: l.checkpoints.map((c) => [r(c.pos.x), r(c.pos.y), r(c.pos.z)]),
      scroll: !!l.scroll,
    };
  }
  writeFileSync(out, JSON.stringify({ _note: "Generated by scripts/export-levels.mjs. Do not edit by hand.", ...levels }) + "\n");
  console.log(`wrote ${path.relative(root, out)} (${Object.keys(levels).length} chapters)`);
} finally {
  await server.close();
}
